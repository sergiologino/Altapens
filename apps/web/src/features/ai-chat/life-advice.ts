/**
 * Простые «житейские» ответы без диагноза. Для серьёзных симптомов — только осторожность и врач.
 * При подключении LLM сюда можно подставить вызов API с жёстким системным промптом.
 */
const DISCLAIMER =
  ' Это не медицинское заключение. При сильной или нарастающей боли, температуре, одышке, обмороке — сразу врач или скорая.'

export function lifeAdviceReply(question: string): string {
  const q = question.trim().toLowerCase()
  if (!q) {
    return `Напишите вопрос одним-двумя предложениями.${DISCLAIMER}`
  }

  if (/бок|под рёбр|в боку|левый бок|правый бок|живот|животе|покалывает|тянет|ноет/.test(q)) {
    return (
      'Часто тянущее или ноющее ощущение в боку без температуры бывает от мышц после сна, неудобной позы или лёгкого переедания. ' +
      'Можно спокойно полежать, выпить воды, понаблюдать пару часов. ' +
      'Если боль резкая, не проходит, усиливается при движении, есть температура или тошнота — нужен очный осмотр.' +
      DISCLAIMER
    )
  }

  if (/голова|головокруж|мигрен|давит в висках/.test(q)) {
    return (
      'Лёгкая головная боль бывает от усталости, жары или нехватки воды. Тише свет, вода, короткий отдых иногда помогают. ' +
      'Если внезапно сильная «громовая» боль, онемение, речь путается или веко «висит» — это срочно.' +
      DISCLAIMER
    )
  }

  if (/давлен|тониометр|пульс высок|пульс низк/.test(q)) {
    return (
      'Цифры давления и пульса лучше обсуждать с лечащим врачом: он знает ваши препараты. ' +
      'Общие бытовые советы — не перегреваться, не спешить после подъёма, пить воду умеренно. ' +
      'При внезапной слабости, боли в груди или спутанности — сразу помощь.' +
      DISCLAIMER
    )
  }

  if (/звонок|мошенник|обман|карта|пароль|перевод денег/.test(q)) {
    return (
      'Если звонок подозрительный: не называйте коды и не переводите деньги. Положите трубку, перезвоните в банк по номеру с карты. ' +
      'Расскажите близким коротко, что произошло.' +
      DISCLAIMER
    )
  }

  return (
    'Я могу подсказать общеизвестные вещи про быт и осторожность. ' +
    'Про болезни, лекарства и «что у меня» в смысле диагноза может сказать только врач после осмотра.' +
    DISCLAIMER
  )
}
